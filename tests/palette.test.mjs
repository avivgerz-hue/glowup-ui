import { test } from "node:test";
import assert from "node:assert/strict";
import { hexToOklch, oklchToHex, buildScale, buildPalette, format } from "../skills/glowup-ui/scripts/palette.mjs";

const SEEDS = ["#17543f", "#7c3aed", "#f59e0b", "#e11d48", "#0ea5e9", "#facc15", "#111827", "#22c55e", "#64748b"];

test("palette: hex → OKLCH → hex round-trips", () => {
  for (const hex of [...SEEDS, "#ffffff", "#000000", "#808080"]) {
    assert.equal(oklchToHex(hexToOklch(hex)), hex);
  }
  const white = hexToOklch("#ffffff");
  assert.ok(Math.abs(white.l - 1) < 1e-3 && white.c < 1e-3);
});

test("palette: scales get darker step by step and keep the seed", () => {
  for (const seed of SEEDS) {
    const { scale, seedStep } = buildScale(seed);
    assert.equal(scale[seedStep], seed, "seed is kept exactly");
    const lightness = Object.values(scale).map((hex) => hexToOklch(hex).l);
    for (let i = 1; i < lightness.length; i++) assert.ok(lightness[i] < lightness[i - 1], `${seed} step ${i} is darker`);
  }
});

test("palette: every role pair passes WCAG AA, light and dark", () => {
  for (const seed of SEEDS) {
    for (const scheme of ["light", "dark"]) {
      const { checks } = buildPalette({ primary: seed, scheme });
      const failed = checks.filter((c) => !c.pass).map((c) => `${c.fg}/${c.bg} ${c.ratio}`);
      assert.deepEqual(failed, [], `${seed} ${scheme}`);
    }
  }
});

test("palette: light brand colors are kept, with dark text on them", () => {
  const amber = buildPalette({ primary: "#f59e0b" }).roles;
  assert.equal(amber.primary, "#f59e0b");
  assert.notEqual(amber["on-primary"], "#ffffff");
  const violet = buildPalette({ primary: "#7c3aed" }).roles;
  assert.equal(violet.primary, "#7c3aed");
  assert.equal(violet["on-primary"], "#ffffff");
});

test("palette: accent scale and output formats", () => {
  const palette = buildPalette({ primary: "#17543f", accent: "#c2410c" });
  assert.ok(palette.scales.accent);
  const css = format(palette, "css");
  assert.match(css, /^\/\* Generated by glowup-ui palette\.mjs/);
  assert.match(css, /:root \{/);
  assert.match(css, /--color-primary-500: #[0-9a-f]{6};/);
  assert.match(css, /--color-on-primary: #ffffff;/);
  assert.match(format(palette, "tailwind"), /@theme \{/);
  assert.deepEqual(Object.keys(JSON.parse(format(palette, "json"))), ["scheme", "scales", "roles", "checks"]);
});
